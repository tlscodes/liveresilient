      // an invalid TXT record; the valid encoding, and the one _txtRdata
      // special-cases the empty payload into, is a single TXT string of
      // length zero: rdlength 1, one 0x00 octet.
      //
      // The packet tail is rdlength (2), rdata (1), OPT record (11).
      final rdlengthAt = packet.length - 14;
      expect(ByteData.sublistView(packet, rdlengthAt).getUint16(0), 1);
      expect(packet[rdlengthAt + 2], 0x00);
      final parsed = TxtQueryWire.parseDnsAnswerPacket(packet);
      expect(parsed.payload, isNotNull);
      expect(parsed.payload, isEmpty);
    });

    test('a TXT string longer than its rdata is clamped, not refused', () {
      // The module's one silent repair: _parseTxtRdata clamps a string length
      // that runs past the end of the rdata (txt_query_wire.dart:477) where
      // every neighbouring malformation - a truncated answer, a truncated
      // rdata - refuses instead. Pinned so a later change to refusal is a
      // visible contract change rather than a silent one.
      final parsed = TxtQueryWire.parseDnsAnswerPacket(
        _packet(
          qdcount: 0,
          ancount: 1,
          body: <int>[
            ..._name('a'),
            0x00, 0x10, // type TXT
            0x00, 0x01, // class IN
            0x00, 0x00, 0x00, 0x00, // ttl
            0x00, 0x04, // rdlength: four octets follow
            0x09, // a TXT string declaring nine of them, with three left
            0x41, 0x42, 0x43,
          ],
        ),
      );
      expect(parsed.payload, <int>[0x41, 0x42, 0x43]);
    });

    test('an rcode wider than the header field is masked to four bits', () {
      // The header carries four rcode bits; anything above 15 belongs in the
      // OPT record's extended rcode octet, which this builder always writes
      // as zero. So rcode 19 reaches the wire as 3, and rcode 16 reaches it
      // as 0 - a NOERROR answer with no record, which a client tells from a
      // successful empty one only by the absent payload.
      final wide = TxtQueryWire.buildDnsAnswerPacket(1, _queryName, const <int>[
        0x41,
      ], rcode: 0x13);
      expect(TxtQueryWire.parseDnsAnswerPacket(wide).rcode, 3);
      expect(ByteData.sublistView(wide).getUint16(6), 0, reason: 'ancount');
      final sixteen = TxtQueryWire.buildDnsAnswerPacket(
        1,
        _queryName,
        const <int>[0x41],
        rcode: 0x10,
      );
      final parsed = TxtQueryWire.parseDnsAnswerPacket(sixteen);
      expect(parsed.rcode, TxtQueryWire.rcodeNoError);
      expect(parsed.payload, isNull);
      // The OPT record's extended rcode, version, flags and rdlength stay
      // zero either way, so nothing carries the lost high bits.
      final opt = ByteData.sublistView(sixteen, sixteen.length - 11);
      expect(opt.getUint32(5), 0, reason: 'extended rcode, version, flags');
      expect(opt.getUint16(9), 0, reason: 'OPT rdlength');
    });

    test('rdata longer than one TXT string rejoins across the split', () {
      // A TXT string is at most 255 octets, so the boundary either side of
      // 255 is where a rejoin bug would show.
      for (final length in <int>[254, 255, 256, 509, 510, 511]) {
        final payload = _bytes(length);
