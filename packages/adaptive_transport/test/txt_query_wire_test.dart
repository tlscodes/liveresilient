  group('chunking into queries and reassembly', () {
    test('a payload survives encode, parse and reassemble at every size', () {
      // 0: a poll. 1: one byte. 3: framed length 5, a whole Base32 block.
      // 4: framed length 6, a partial block. 37: exactly one full label.
      // 38 and 200: more chunks than one query can carry.
      for (final length in <int>[0, 1, 3, 4, 37, 38, 200]) {
        final payload = _bytes(length);
        expect(_roundTrip(payload), payload, reason: 'length $length');
      }
    });

    test('the chunk count follows the framed length, not the payload', () {
      expect(
        TxtQueryWire.encodeQueries(_bytes(0), _domain).names,
        hasLength(1),
      );
      expect(
        TxtQueryWire.encodeQueries(_bytes(37), _domain).names,
        hasLength(1),
      );
      expect(
        TxtQueryWire.encodeQueries(_bytes(38), _domain).names,
        hasLength(2),
      );
      expect(
        TxtQueryWire.encodeQueries(_bytes(200), _domain).names,
        hasLength(6),
      );
    });

    test('every name of one payload carries the same session and a nonce', () {
      final encoded = TxtQueryWire.encodeQueries(_bytes(200), _domain);
      // Not hasLength(sessionChars): newSessionId is encodeInt(_, sessionChars)
      // and encodeInt fills a list of exactly that width, so the length is a
      // structural identity. The alphabet is the part that can go wrong.
      final session = RegExp('^[A-Z2-7]{${TxtQueryWire.sessionChars}}\$');
      expect(
        session.hasMatch(encoded.sessionId),
        isTrue,
        reason: encoded.sessionId,
      );
      final nonce = RegExp('^[A-Z2-7]{${TxtQueryWire.nonceChars}}\$');
      for (var seq = 0; seq < encoded.names.length; seq++) {
        final parts = encoded.names[seq].split('.');
        expect(parts[0], TxtQueryWire.marker);
        expect(TxtQueryWire.decodeSeq(parts[1]), seq);
        expect(parts[2], encoded.sessionId);
        expect(nonce.hasMatch(parts[3]), isTrue, reason: parts[3]);
        expect(encoded.names[seq], endsWith('.tunnel.$_domain'));
      }
    });

    test('a supplied session id is used instead of a fresh one', () {
      final encoded = TxtQueryWire.encodeQueries(
        _bytes(50),
        _domain,
        sessionId: _session,
      );
      expect(encoded.sessionId, _session);
      expect(encoded.names.every((n) => n.contains('.$_session.')), isTrue);
    });

    test('reassembly does not depend on the order chunks arrive in', () {
      final payload = _bytes(200);
      final parsed = _parseAll(
        TxtQueryWire.encodeQueries(payload, _domain, sessionId: _session),
      );
      expect(parsed, hasLength(6));
      expect(TxtQueryWire.reassemble(parsed.reversed.toList()), payload);
      const shuffled = <int>[3, 0, 5, 1, 4, 2];
      expect(
        TxtQueryWire.reassemble(<ParsedTxtQuery>[
          for (final i in shuffled) parsed[i],
        ]),
        payload,
      );
    });

    test('a duplicate identical chunk is accepted', () {
      final payload = _bytes(60);
      final parsed = _parseAll(
        TxtQueryWire.encodeQueries(payload, _domain, sessionId: _session),
