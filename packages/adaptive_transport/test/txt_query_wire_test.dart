import 'dart:typed_data';

import 'package:adaptive_transport/adaptive_transport.dart';
import 'package:test/test.dart';

/// Contract suite for [TxtQueryWire] — the pure codec under the TXT query
/// fallback lane.
///
/// This file pins the boundaries and the refusals. Every
/// `TxtQueryWireException` the module can raise is a documented contract with
/// a far side that cannot be patched in the same release, so each throw site
/// gets a case here, keyed on its message rather than only its type.
///
/// It is NOT independently sufficient, and is not meant to be. Most of what
/// follows is `decode(encode(x)) == x`, which a symmetric error satisfies: a
/// permuted alphabet, a swapped seq endianness or a mirrored chunk order all
/// survive a round trip. The absolute byte truth lives in the golden-vector
/// suite `test/resilient/txt_query_wire_test.dart`, which pins this codec
/// against vectors generated by the Python responder. Delete that file and
/// this one stops proving the wire format; the few literal vectors here
/// (`'AE'`, `'32WQ'`, the `encodeInt` values) are landmarks, not the pinning.
///
/// Everything is pure computation over bytes: no socket, no timer, no clock,
/// no unseeded randomness. Where the module draws from the platform CSPRNG
/// (session ids, nonces) the assertions are on shape and distribution, never
/// on a value.
void main() {
  group('Base32 round trips', () {
    test('the empty payload encodes as the out-of-alphabet marker', () {
      // A DNS label cannot be empty, so the empty chunk needs a character
      // that Base32 itself can never produce.
      expect(TxtQueryWire.base32Encode(const <int>[]), '0');
      expect(TxtQueryWire.base32Decode('0'), isEmpty);
    });

    test('a one-byte payload survives the 8/5 expansion', () {
      expect(TxtQueryWire.base32Encode(const <int>[0x01]), 'AE');
      expect(TxtQueryWire.base32Decode('AE'), <int>[0x01]);
      expect(
        TxtQueryWire.base32Decode(TxtQueryWire.base32Encode(const <int>[0xFF])),
        <int>[0xFF],
      );
    });

    test('a payload on a block boundary encodes with no leftover bits', () {
      for (final length in <int>[5, 10, 35]) {
        final bytes = _bytes(length);
        final encoded = TxtQueryWire.base32Encode(bytes);
        expect(
          encoded.length % 8,
          0,
          reason: '$length bytes is a whole number of 40-bit blocks',
        );
        expect(encoded.length, length * 8 ~/ 5);
        expect(TxtQueryWire.base32Decode(encoded), bytes);
      }
    });

    test('a payload off the block boundary keeps its partial character', () {
      for (final length in <int>[1, 2, 3, 4, 6, 7, 39]) {
        final bytes = _bytes(length);
        final encoded = TxtQueryWire.base32Encode(bytes);
        expect(
          encoded.length,
          (length * 8 + 4) ~/ 5,
          reason: 'the trailing bits still need a character of their own',
        );
        expect(TxtQueryWire.base32Decode(encoded), bytes);
      }
    });

    test('every length that fits one label round-trips exactly', () {
      for (var length = 0; length <= TxtQueryWire.rawPerLabel; length++) {
        final bytes = _bytes(length);
        expect(
          TxtQueryWire.base32Decode(TxtQueryWire.base32Encode(bytes)),
          bytes,
          reason: 'length $length',
        );
      }
    });

    test('the output stays inside the RFC 4648 alphabet', () {
      final alphabet = RegExp(r'^[A-Z2-7]+$');
      for (var length = 1; length <= TxtQueryWire.rawPerLabel; length++) {
        expect(
          alphabet.hasMatch(TxtQueryWire.base32Encode(_bytes(length))),
          isTrue,
        );
      }
    });

    test('decoding is case-insensitive and tolerates padding', () {
      final bytes = _bytes(11);
      final encoded = TxtQueryWire.base32Encode(bytes);
      expect(TxtQueryWire.base32Decode(encoded.toLowerCase()), bytes);
      expect(TxtQueryWire.base32Decode('$encoded======'), bytes);
      expect(TxtQueryWire.base32Decode('0'.toUpperCase()), isEmpty);
    });
  });

  group('Base32 refusals', () {
    test('a length no whole number of octets can produce is refused', () {
      // 1, 3 and 6 characters past a block are the residues Base32 cannot
      // reach from whole bytes: the label lost or gained characters.
      for (final length in <int>[1, 3, 6, 9, 11, 14]) {
        expect(
          () => TxtQueryWire.base32Decode('A' * length),
          _wireError('bad Base32 length $length'),
          reason: 'residue ${length % 8}',
        );
      }
    });

    test('a character outside the alphabet is refused', () {
      expect(TxtQueryWire.base32Decode('AAAAAAAA'), hasLength(5));
      expect(
        () => TxtQueryWire.base32Decode('AAAAAAA1'),
        _wireError('illegal Base32 char 1'),
      );
      expect(
        () => TxtQueryWire.base32Decode('AB!DEFGH'),
        _wireError('illegal Base32 char !'),
      );
      expect(
        () => TxtQueryWire.decodeInt('A0'),
        _wireError('illegal Base32 char 0'),
      );
    });
  });

  group('fixed-width integers', () {
    test('encode big-endian into exactly the requested width', () {
      expect(TxtQueryWire.encodeInt(0, 2), 'AA');
      expect(TxtQueryWire.encodeInt(1, 2), 'AB');
      expect(TxtQueryWire.encodeInt(31, 1), '7');
      expect(TxtQueryWire.encodeInt(32, 2), 'BA');
      expect(TxtQueryWire.encodeInt(1023, 2), '77');
      expect(TxtQueryWire.encodeInt(0, 6), 'AAAAAA');
    });

    test('decode is the inverse and ignores case', () {
      for (var value = 0; value < 1024; value++) {
        final label = TxtQueryWire.encodeInt(value, 2);
        expect(TxtQueryWire.decodeInt(label), value);
        expect(TxtQueryWire.decodeInt(label.toLowerCase()), value);
      }
    });

    test('a value too wide for its field is refused', () {
      expect(
        () => TxtQueryWire.encodeInt(32, 1),
        _wireError('32 does not fit in 1 chars'),
      );
      expect(
        () => TxtQueryWire.encodeInt(1024, 2),
        _wireError('1024 does not fit in 2 chars'),
      );
      expect(
        () => TxtQueryWire.encodeInt(-1, 2),
        _wireError('negative value -1'),
      );
    });

    test('a sequence number outside the label range is refused', () {
      expect(TxtQueryWire.encodeSeq(0), 'AA');
      expect(TxtQueryWire.encodeSeq(TxtQueryWire.seqMax), '77');
      expect(
        () => TxtQueryWire.encodeSeq(TxtQueryWire.seqMax + 1),
        _wireError('seq 1024 out of 0..1023'),
      );
      expect(() => TxtQueryWire.encodeSeq(-1), _wireError('seq -1 out of'));
      expect(
        () => TxtQueryWire.decodeSeq('BAA'),
        _wireError('seq 1024 out of range'),
      );
    });

    test('every sequence number the label can hold round-trips', () {
      for (var seq = 0; seq <= TxtQueryWire.seqMax; seq++) {
        final label = TxtQueryWire.encodeSeq(seq);
        expect(label.length, TxtQueryWire.seqChars);
        expect(TxtQueryWire.decodeSeq(label), seq);
      }
    });

    test('session ids and nonces have the declared shape', () {
      // Values come from the platform CSPRNG, so only shape is assertable.
      // Note the range is NOT assertable here: every string matching these
      // patterns is below 2^30 / 2^20 by construction, so `lessThan` on the
      // decoded value would hold for any six characters at all.
      final session = RegExp('^[A-Z2-7]{${TxtQueryWire.sessionChars}}\$');
      final nonce = RegExp('^[A-Z2-7]{${TxtQueryWire.nonceChars}}\$');
      for (var i = 0; i < 64; i++) {
        final id = TxtQueryWire.newSessionId();
        final once = TxtQueryWire.newNonce();
        expect(session.hasMatch(id), isTrue, reason: id);
        expect(nonce.hasMatch(once), isTrue, reason: once);
      }
    });

    test('a session id is drawn fresh, not reused', () {
      // A generator stuck on one value keeps every name of every session
      // colliding in the responder's reassembly table, and passes every
      // shape assertion above. 30 bits over 64 draws: the chance of even
      // four collisions is far below one in a million.
      final ids = <String>{
        for (var i = 0; i < 64; i++) TxtQueryWire.newSessionId(),
      };
      expect(ids, hasLength(greaterThan(60)));
    });

    test('the high bits of a session id are random, not padding', () {
      // The bit loop in _randomBits takes 24 bits at a time and must run
      // twice for a 30-bit id. A version that ran it once would still emit
      // six alphabet characters and still decode below 2^30, but bits 25..29
      // would be zero, so the first character would always be 'A'. Against a
      // correct generator this holds with probability 1 - 32 * (1/32)^128.
      final leads = <String>{
        for (var i = 0; i < 128; i++) TxtQueryWire.newSessionId()[0],
      };
      expect(leads, hasLength(greaterThan(1)));
    });
  });

  group('up-frame framing', () {
    test('a framed payload carries its own u16 length', () {
      expect(TxtQueryWire.frameUp(const <int>[]), <int>[0, 0]);
      expect(TxtQueryWire.frameUp(const <int>[0x41]), <int>[0, 1, 0x41]);
      final long = _bytes(300);
      final framed = TxtQueryWire.frameUp(long);
      expect(framed.length, long.length + TxtQueryWire.frameHeader);
      expect(framed[0], 300 >> 8);
      expect(framed[1], 300 & 0xFF);
      expect(TxtQueryWire.unframeUp(framed), long);
    });

    test('every framed length round-trips through unframing', () {
      for (final length in <int>[0, 1, 39, 255, 256, 1150]) {
        final payload = _bytes(length);
        expect(
          TxtQueryWire.unframeUp(TxtQueryWire.frameUp(payload)),
          payload,
          reason: 'length $length',
        );
      }
    });

    test('the u16 length field is the payload ceiling', () {
      final atLimit = Uint8List(0xFFFF);
      expect(TxtQueryWire.frameUp(atLimit), hasLength(0xFFFF + 2));
      expect(
        () => TxtQueryWire.frameUp(Uint8List(0x10000)),
        _wireError('payload exceeds u16'),
      );
    });

    test('a frame shorter than its header is refused', () {
      expect(
        () => TxtQueryWire.unframeUp(const <int>[]),
        _wireError('truncated frame'),
      );
      expect(
        () => TxtQueryWire.unframeUp(const <int>[0]),
        _wireError('truncated frame'),
      );
    });

    test('a frame whose body arrived short is refused', () {
      expect(
        () => TxtQueryWire.unframeUp(const <int>[0, 5, 1, 2]),
        _wireError('incomplete frame have=2 want=5'),
      );
      final framed = TxtQueryWire.frameUp(_bytes(64));
      expect(
        () => TxtQueryWire.unframeUp(framed.sublist(0, framed.length - 1)),
        _wireError('incomplete frame have=63 want=64'),
      );
    });

    test('bytes past the declared length are not handed up', () {
      expect(TxtQueryWire.unframeUp(const <int>[0, 1, 0x41, 0x42]), <int>[
        0x41,
      ]);
    });

    test('the downstream budget is a hard edge', () {
      final atBudget = _bytes(TxtQueryWire.downstreamBudget);
      expect(
        TxtQueryWire.unframeDown(TxtQueryWire.frameDown(atBudget)),
        atBudget,
      );
      expect(
        () => TxtQueryWire.frameDown(
          Uint8List(TxtQueryWire.downstreamBudget + 1),
        ),
        _wireError('downstream 1151 > 1150'),
      );
    });
  });

  group('chunking', () {
    test('an empty buffer is still one chunk, so a poll is a real query', () {
      expect(TxtQueryWire.splitChunks(Uint8List(0)), <Object>[isEmpty]);
      expect(TxtQueryWire.splitChunks(Uint8List(0)), hasLength(1));
    });

    test('a buffer that lands on the label boundary makes no short tail', () {
      final exact = TxtQueryWire.splitChunks(
        Uint8List(TxtQueryWire.rawPerLabel * 2),
      );
      expect(exact.map((c) => c.length), <int>[39, 39]);
      final one = TxtQueryWire.splitChunks(Uint8List(TxtQueryWire.rawPerLabel));
      expect(one.map((c) => c.length), <int>[39]);
    });

    test('a buffer past the boundary opens exactly one more chunk', () {
      final chunks = TxtQueryWire.splitChunks(
        Uint8List(TxtQueryWire.rawPerLabel * 2 + 1),
      );
      expect(chunks.map((c) => c.length), <int>[39, 39, 1]);
    });

    test('the chunks concatenate back to the buffer they came from', () {
      final framed = TxtQueryWire.frameUp(_bytes(200));
      final rejoined = <int>[
        for (final chunk in TxtQueryWire.splitChunks(framed)) ...chunk,
      ];
      expect(rejoined, framed);
    });
  });

  group('query names', () {
    test('a built name has the documented label layout', () {
      final name = TxtQueryWire.buildQueryName(
        const <int>[0xDE, 0xAD],
        5,
        _session,
        _nonce,
        _domain,
      );
      expect(name.split('.'), <String>[
        'q',
        'AF',
        _session,
        _nonce,
        '32WQ',
        'tunnel',
        'valve',
        'example',
      ]);
    });

    test('a built name parses back to the fields that built it', () {
      final chunk = _bytes(17);
      final built = TxtQueryWire.buildQueryName(
        chunk,
        300,
        _session,
        _nonce,
        _domain,
      );
      final parsed = TxtQueryWire.parseQueryName(built, _domain);
      expect(parsed.seq, 300);
      expect(parsed.chunk, chunk);
      expect(parsed.domain, _domain);
      // DNS names are case-insensitive, so the parser lowercases the whole
      // name: the session and nonce come back in lower case, never equal to
      // the upper-case labels the builder emitted.
      expect(parsed.sessionId, _session.toLowerCase());
      expect(parsed.nonce, _nonce.toLowerCase());
      // Against the name that was built, not against itself: a parser handing
      // back an empty string, the head labels alone or the zone alone would
      // satisfy any comparison of this field with its own lower case.
      expect(parsed.name, built.toLowerCase());
    });

    test('the builder lowercases the zone it was handed', () {
      // Only the parse side lowercases in the round-trip cases, so a builder
      // that stopped doing it would go unseen there while emitting names the
      // responder's own comparison misses.
      expect(
        TxtQueryWire.buildQueryName(
          const <int>[],
          0,
          _session,
          _nonce,
          'VALVE.Example',
        ),
        _queryName,
      );
    });

    test('leading and trailing dots are stripped on both sides', () {
      final parsed = TxtQueryWire.parseQueryName(
        '.Q.AF.$_session.$_nonce.32WQ.TUNNEL.Valve.Example.',
        '.$_domain.',
      );
      expect(parsed.seq, 5);
      expect(parsed.chunk, <int>[0xDE, 0xAD]);
      expect(parsed.domain, _domain);
    });

    test('a name from another zone is refused', () {
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.$_session.$_nonce.32WQ.tunnel.other.example',
          _domain,
        ),
        _wireError('not a valve query for "valve.example"'),
      );
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.$_session.$_nonce.32WQ.valve.example',
          _domain,
        ),
        _wireError('not a valve query'),
      );
      expect(
        () => TxtQueryWire.parseQueryName('tunnel.valve.example', _domain),
        _wireError('not a valve query'),
      );
    });

    test('a head of the wrong length or marker is refused', () {
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.$_session.$_nonce.32WQ.EXTRA.tunnel.$_domain',
          _domain,
        ),
        _wireError('bad head'),
      );
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.$_session.$_nonce.tunnel.$_domain',
          _domain,
        ),
        _wireError('bad head'),
      );
      expect(
        () => TxtQueryWire.parseQueryName(
          'x.AF.$_session.$_nonce.32WQ.tunnel.$_domain',
          _domain,
        ),
        _wireError('bad head'),
      );
    });

    test('a session or nonce label of the wrong width is refused', () {
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.ABC23.$_nonce.32WQ.tunnel.$_domain',
          _domain,
        ),
        _wireError('session/nonce width'),
      );
      expect(
        () => TxtQueryWire.parseQueryName(
          'q.AF.$_session.7XY.32WQ.tunnel.$_domain',
          _domain,
        ),
        _wireError('session/nonce width'),
      );
    });

    test('a payload label wider than a DNS label is refused', () {
      final full = Uint8List(TxtQueryWire.rawPerLabel);
      expect(
        TxtQueryWire.buildQueryName(
          full,
          0,
          _session,
          _nonce,
          _domain,
        ).split('.')[4].length,
        TxtQueryWire.labelMax,
      );
      expect(
        () => TxtQueryWire.buildQueryName(
          Uint8List(TxtQueryWire.rawPerLabel + 1),
          0,
          _session,
          _nonce,
          _domain,
        ),
        _wireError('payload label 64 > 63'),
      );
    });

    test('an empty or over-long label is refused', () {
      expect(
        () =>
            TxtQueryWire.buildQueryName(const <int>[], 0, '', _nonce, _domain),
        _wireError('bad label ""'),
      );
      final wide = 'a' * (TxtQueryWire.labelMax + 1);
      expect(
        () => TxtQueryWire.buildQueryName(
          const <int>[],
          0,
          _session,
          _nonce,
          '$wide.co',
        ),
        _wireError('bad label "$wide"'),
      );
      final atLimit = 'a' * TxtQueryWire.labelMax;
      expect(
        TxtQueryWire.buildQueryName(
          const <int>[],
          0,
          _session,
          _nonce,
          '$atLimit.co',
        ),
        endsWith('.tunnel.$atLimit.co'),
      );
    });

    test('the longest name the FQDN limit allows passes, one more throws', () {
      final chunk = Uint8List(TxtQueryWire.rawPerLabel);
      final name = TxtQueryWire.buildQueryName(
        chunk,
        0,
        _session,
        _nonce,
        _zoneOfLength(165),
      );
      expect(name.length, TxtQueryWire.fqdnMax);
      expect(
        () => TxtQueryWire.buildQueryName(
          chunk,
          0,
          _session,
          _nonce,
          _zoneOfLength(166),
        ),
        _wireError('FQDN 254 > 253'),
      );
    });

    test('an empty interior label parses, though no builder emits one', () {
      // Pinned as it stands, not endorsed. buildQueryName refuses an empty
      // label (txt_query_wire.dart:252-256); parseQueryName never checks for
      // one, so names no builder produced parse anyway.
      //
