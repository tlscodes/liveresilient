      // what the '0' marker means (txt_query_wire.dart:23-24). Two distinct
      // names therefore carry one query - the aliasing the marker exists to
      // remove. Reported as a defect, left unfixed here.
      final viaEmpty = TxtQueryWire.parseQueryName(
        'q.AF.$_session.$_nonce..tunnel.$_domain',
        _domain,
      );
      final viaMarker = TxtQueryWire.parseQueryName(
        'q.AF.$_session.$_nonce.0.tunnel.$_domain',
        _domain,
      );
      expect(viaEmpty.seq, 5);
      expect(viaEmpty.chunk, isEmpty);
      expect(viaEmpty.chunk, viaMarker.chunk);
      expect(viaEmpty.name, isNot(viaMarker.name));

      // An empty seq label decodes to zero, so it aliases 'AA' the same way.
      expect(
        TxtQueryWire.parseQueryName(
          'q..$_session.$_nonce.0.tunnel.$_domain',
          _domain,
        ).seq,
        0,
      );
    });

