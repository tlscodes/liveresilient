      expect(
        TxtQueryWire.reassemble(<ParsedTxtQuery>[
          ...parsed,
          parsed.first,
          parsed.last,
        ]),
        payload,
      );
    });

    test('a duplicate conflicting chunk is refused', () {
      expect(
        () => TxtQueryWire.reassemble(<ParsedTxtQuery>[
          _part(0, const <int>[0, 1, 0x41]),
          _part(0, const <int>[0, 1, 0x42]),
        ]),
        _wireError('conflict at seq 0'),
      );
      // Same seq, one chunk a proper prefix of the other: a comparison that
      // stopped at the shorter length would accept the truncated copy of a
