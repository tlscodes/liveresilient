    test('labels ahead of a pointer stay in front of the name it names', () {
      // The ordinary compressed form: some literal labels, then a pointer to
      // a suffix written earlier in the packet. Every other pointer case in
      // this file and in the golden-vector suite replaces the whole name with
      // a pointer, so the seam - labels collected before the jump, then the
      // decoded target - never runs with anything in front of it.
      //
      // Offsets: the question name starts at 12, its type and class follow,
      // and the pointed-at name sits at 20.
      expect(
        TxtQueryWire.parseDnsQueryPacket(
          _packet(body: <int>[0x01, 0x62, 0xC0, 20, ..._txtIn, ..._name('a')]),
        ).name,
        'b.a',
      );
      // Two labels ahead of a two-label target, so a reversed join shows as
      // an order rather than as a swap.
      expect(
        TxtQueryWire.parseDnsQueryPacket(
          _packet(
            body: <int>[
              0x02, 0x77, 0x77, // "ww"
              0x01, 0x78, // "x"
              0xC0, 23, // the rest of the name lives at offset 23
              ..._txtIn,
              ..._name('a.b'),
            ],
          ),
        ).name,
        'ww.x.a.b',
      );
    });

    test('an empty label is skipped, not written as a zero length', () {
      // A zero length octet is the end-of-name marker, so writing one for an
      // empty label would truncate the name on the wire. Both forms a caller
      // can hand in - a doubled dot and a trailing dot - encode to the same
      // two-label name.
      for (final name in <String>['a..b', 'a.b.']) {
        expect(
          TxtQueryWire.parseDnsQueryPacket(
            TxtQueryWire.buildDnsQueryPacket(1, name),
