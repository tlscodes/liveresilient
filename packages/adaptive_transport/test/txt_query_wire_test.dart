const String _domain = 'valve.example';
const String _session = 'ABC234';
const String _nonce = '7XYZ';
const String _queryName = 'q.AA.ABC234.7XYZ.0.tunnel.valve.example';

/// A TXT/IN question tail, for hand-built packets.
const List<int> _txtIn = <int>[0x00, 0x10, 0x00, 0x01];

/// Deterministic bytes: no clock, no unseeded randomness.
Uint8List _bytes(int length) =>
    Uint8List.fromList(List<int>.generate(length, (i) => (i * 31 + 7) & 0xFF));

/// Matches a [TxtQueryWireException] whose message contains [fragment], so a
/// case pins the contract it names rather than any refusal at all.
Matcher _wireError(String fragment) => throwsA(
  isA<TxtQueryWireException>().having(
    (e) => e.message,
    'message',
    contains(fragment),
  ),
);

/// A zone of exactly [total] characters, in labels the wire accepts.
String _zoneOfLength(int total) {
  final labels = <String>[];
  var left = total;
  while (left > TxtQueryWire.labelMax) {
    labels.add('a' * TxtQueryWire.labelMax);
    left -= TxtQueryWire.labelMax + 1; // the label and its separating dot
  }
  labels.add('a' * left);
  return labels.join('.');
}

List<ParsedTxtQuery> _parseAll(EncodedQueries encoded) => <ParsedTxtQuery>[
  for (final name in encoded.names) TxtQueryWire.parseQueryName(name, _domain),
];

Uint8List _roundTrip(Uint8List payload) => TxtQueryWire.reassemble(
  _parseAll(TxtQueryWire.encodeQueries(payload, _domain, sessionId: _session)),
);

ParsedTxtQuery _part(int seq, List<int> chunk) => ParsedTxtQuery(
  seq: seq,
  sessionId: _session.toLowerCase(),
  nonce: _nonce.toLowerCase(),
  chunk: Uint8List.fromList(chunk),
  domain: _domain,
  name: 'synthetic',
);

/// A name in DNS label form, without compression.
List<int> _name(String text) => <int>[
  for (final label in text.split('.')) ...<int>[
    label.length,
    ...label.codeUnits,
  ],
  0,
];

/// A 12-octet DNS header followed by [body].
Uint8List _packet({
  int txid = 0x2A2A,
  int flags = 0x0100,
  int qdcount = 1,
  int ancount = 0,
  List<int> body = const <int>[],
}) {
  final header = ByteData(12);
  header.setUint16(0, txid);
  header.setUint16(2, flags);
  header.setUint16(4, qdcount);
  header.setUint16(6, ancount);
  return Uint8List.fromList(<int>[...header.buffer.asUint8List(), ...body]);
}

/// A query packet whose question name is a chain of [hops] compression
/// pointers ending in the literal name `a`.
///
/// The first pointer sits at offset 12, the question type and class follow it
/// at 14, and the rest of the chain starts at 18 so the question stays
/// parseable. Each hop is one level of `_decodeName` recursion.
Uint8List _pointerChain(int hops) {
  final body = <int>[
    0xC0, 18, // the question name: a pointer into the chain
    ..._txtIn,
  ];
  for (var i = 1; i < hops; i++) {
    body.addAll(<int>[0xC0, 18 + 2 * i]);
  }
  body.addAll(_name('a'));
  return _packet(body: body);
}
